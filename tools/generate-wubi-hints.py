"""Derive UI key-name hints from the project's existing Wubi86 encoder facts."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'crates/wubi-encoder/src/lib.rs'
OUTPUT = ROOT / 'platforms/macos/Sources/WubiHints.generated.swift'


def generate():
    block = SOURCE.read_text().split('const KEY_NAMES:', 1)[1].split('];', 1)[0]
    pairs = re.findall(r"\('([a-y])', '([^']+)'\)", block)
    if [key for key, _ in pairs] != list('abcdefghijklmnopqrstuvwxy'):
        raise ValueError('expected exactly 25 ordered Wubi86 key names')
    mapping = ',\n'.join(f'        "{key}": "{name}"' for key, name in pairs)
    return '''// Generated by tools/generate-wubi-hints.py; source D13. Do not edit.
// SPDX-License-Identifier: GPL-3.0-or-later
import Foundation

enum WubiHints {
    private static let keyNames: [Character: String] = [
''' + mapping + '''
    ]
    static func text(buffer: String, mode: String, english: Bool, wildcard: Bool) -> String? {
        guard !english, mode != "pinyin", !buffer.isEmpty, buffer.utf8.count <= 4 else { return nil }
        var parts: [String] = []
        for key in buffer {
            if key == "z", wildcard { parts.append("Z 通配") }
            else if let name = keyNames[key] { parts.append("\\(String(key).uppercased()) \\(name)") }
            else { return nil }
        }
        return "键位提示：" + parts.joined(separator: " · ")
    }
}
'''


if __name__ == '__main__':
    OUTPUT.write_text(generate())
