"""Build a compact offline full-code index; reject unverified or PUA teaching rows."""
from pathlib import Path
import hashlib
import json
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/generated/wubi86-single.tsv'
ROOTS = ROOT / 'data/learning/wubi86-roots.tsv'
VERIFIED = ROOT / 'data/learning/wubi86-verified.tsv'
KEYS = ROOT / 'data/learning/wubi86-readable-keys.tsv'
D2 = ROOT / 'data/sources/wubi-lex-86.txt'
OUTPUT = ROOT / 'data/generated/wubi86-learning-codes.bin'
REPORT = ROOT / 'data/generated/wubi86-learning-report.json'


def full_codes():
    result = {}
    for line in SOURCE.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        code, text, _ = line.split('\t')
        if len(text) != 1 or not re.fullmatch('[a-y]{1,4}', code) or text in result:
            raise ValueError('invalid or duplicate primary single-character entry')
        result[text] = code
    return result


def generate_roots(codes):
    if hashlib.sha256(D2.read_bytes()).hexdigest() != 'da8a20e6af3446348d5d68a89ac71d5e3b9b17b00446d8204ac1e9529626697f':
        raise ValueError('D2 source hash mismatch')
    key_map = {}
    for line in KEYS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        key, glyphs = line.split('\t')
        for glyph in glyphs:
            if glyph in key_map:
                raise ValueError('ambiguous readable key fact')
            key_map[glyph] = key
    records = {}
    for line in VERIFIED.read_text().splitlines():
        if line and not line.startswith('#'):
            character = line.split('\t')[0]
            if character in records:
                raise ValueError('duplicate verified teaching character')
            records[character] = line
    strokes = {'一': 'g', '丨': 'h', '亅': 'h', '丿': 't', '丶': 'y',
               '乚': 'n', '乙': 'n', '𠃌': 'n', 'ㄥ': 'n', 'ㄋ': 'n', 'ㄅ': 'n'}
    for line in D2.read_text(encoding='utf-8-sig').splitlines():
        fields = line.split('\t')
        if len(fields) != 2:
            continue
        char, roots = fields
        code = codes.get(char)
        if not code or char in records or not roots or len(roots) > 16:
            continue
        if roots[0] == char:
            if char not in key_map or not 2 <= len(roots) <= 4 or not all(g in strokes for g in roots[1:]):
                continue
            keys = key_map[char] + ''.join(strokes[g] for g in roots[1:])
            if keys != code:
                continue
            positions = ['首笔', '次笔', '末笔']
            pairs = [char + ':' + key_map[char]] + [positions[i] + glyph + ':' + strokes[glyph]
                for i, glyph in enumerate(roots[1:])]
            rule = '成字字根：报户口' + key_map[char].upper() + '，再取' + ('首、次笔' if len(roots) == 3 else '首、次、末笔' if len(roots) == 4 else '首笔')
            records[char] = '\t'.join([char, code, 'chengzi', rule, ' '.join(pairs), '-'])
            continue
        if len(roots) >= 4 and all(g in key_map for g in roots):
            keys = ''.join(key_map[g] for g in roots)
            if keys[:3] + keys[-1] == code:
                records[char] = '\t'.join([char, code, 'selected_roots',
                    '按码位展示已核验字形；完整拆分说明暂缺',
                    ' '.join(g + ':' + key_map[g] for g in roots[:3] + roots[-1]), '-'])
                continue
        # Some D2 suffixes are ambiguous with ordinary strokes. Never call them recognition codes.
        for prefix in (roots, roots[:-1]):
            if 2 <= len(prefix) <= 3 and all(g in key_map for g in prefix):
                keys = ''.join(key_map[g] for g in prefix)
                if len(code) == len(keys) + 1 and code.startswith(keys):
                    records[char] = '\t'.join([char, code, 'partial',
                        '已核验取码字根；末码' + code[-1].upper() + '说明暂缺',
                        ' '.join(g + ':' + key_map[g] for g in prefix), '-'])
                    break
    header = '# SPDX-License-Identifier: CC-BY-SA-4.0\n# Generated by tools/prepare-wubi-learning.py; source D2 MIT, Copyright (c) 2019 aardio.\n# Project key facts and verified modifications: D14. See packaging/licenses/D2-MIT.txt.\n# Categories preserve uncertainty; no PUA or oracle code columns.\n'
    ROOTS.write_text(header + ''.join(records[c] + '\n' for c in sorted(records)))
    counts = {}
    for row in records.values():
        category = row.split('\t')[2]
        counts[category] = counts.get(category, 0) + 1
    return counts


def check_roots(codes):
    seen = set()
    for line in ROOTS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        text, code, category, rule, pairs, recognition = line.split('\t')
        if text in seen or codes.get(text) != code or category not in ('key_name', 'compound', 'chengzi', 'selected_roots', 'partial', 'stroke'):
            raise ValueError('invalid teaching identity/code/category')
        seen.add(text)
        if any(0xE000 <= ord(c) <= 0xF8FF or 0xF0000 <= ord(c) <= 0x10FFFF for c in line):
            raise ValueError('PUA/supplementary private glyph not allowed')
        units = [p.rsplit(':', 1) for p in pairs.split()]
        if not rule or not units or any(len(k) != 1 or k not in 'abcdefghijklmnopqrstuvwxy' or not root for root, k in units):
            raise ValueError('invalid readable root/key pair')
        keys = ''.join(k for _, k in units)
        if recognition != '-':
            description, key = recognition.rsplit(':', 1)
            if not description or len(key) != 1:
                raise ValueError('invalid recognition')
            keys += key
        if category == 'key_name':
            keys *= 4
        if category == 'selected_roots':
            keys = keys[:3] + keys[-1]
        expected = code[:-1] if category == 'partial' else code
        if keys != expected:
            raise ValueError('teaching root keys do not reproduce the declared code portion: ' + text)
    return seen


def build():
    codes = full_codes()
    categories = generate_roots(codes)
    covered = check_roots(codes)
    raw = b''.join(struct.pack('<I', ord(text)) + code.encode().ljust(4, b'\0')
                   for text, code in sorted(codes.items()))
    OUTPUT.write_bytes(raw)
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    report = {'source_sha256': digest(SOURCE), 'roots_sha256': digest(ROOTS),
              'index_sha256': digest(OUTPUT), 'index_bytes': len(raw),
              'full_code_characters': len(codes), 'teaching_records': len(covered), 'categories': categories,
              'fully_verified_explanations': categories.get('key_name', 0) + categories.get('compound', 0) + categories.get('chengzi', 0) + categories.get('stroke', 0),
              'verified_source_sha256': digest(VERIFIED), 'key_facts_sha256': digest(KEYS),
              'd2_sha256': digest(D2), 'generator_sha256': digest(Path(__file__)),
              'unexplained_characters': len(codes) - len(covered),
              'oracle_code_columns_published': False,
              'note': 'Types distinguish verified explanation, selected roots and partial data. Partial suffix semantics are explicitly missing.'}
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(report, ensure_ascii=False))


if __name__ == '__main__':
    build()
