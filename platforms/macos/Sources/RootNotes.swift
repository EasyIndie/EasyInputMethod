// 字根辨识标注（ADR-374）：几个字形在常见字体里几乎一样，只靠字形猜不出是哪个字根。
//
// 这里只放**面向用户的辨识短语**（UI 文案，不是词典数据）：字根本身来自
// modules/keymap/data/key-roots-wubi86.tsv，本表只补一句"怎么认"。
enum RootNotes {
    /// 字根字形 → 辨识短语。只收真的会同形混淆的字根，避免每道题都堆字。
    static let notes: [String: String] = [
        "口": "嘴巴，如「吃」「吗」",
        "囗": "包围外框，如「国」「园」",
        "曰": "扁日，如「曹」「曾」",
        "日": "日子，如「明」「时」",
        "目": "眼睛，如「眼」「眠」",
        "且": "而且，如「组」「祖」",
        "罒": "扁四，如「罗」「罪」",
        "田": "田地，如「男」「界」",
        "甲": "甲片，如「鸭」「匣」",
        "由": "由，如「邮」「笛」",
        "冂": "同字框，如「同」「周」",
        "凵": "凶字框，如「凶」「击」",
        "匚": "区字框，如「区」「匠」",
        "己": "自己，如「记」「纪」",
        "巳": "巳，如「包」「导」",
    ]

    static func note(for glyph: String) -> String? { notes[glyph] }

    /// 字根题题干上方那行：有辨识短语时写成「字根 · 口（嘴巴，如「吃」「吗」）」。
    static func caption(for glyph: String) -> String {
        guard let note = notes[glyph] else { return "字根" }
        return "字根 · \(glyph)（\(note)）"
    }
}
